export function getAllMemories(): MemoryItem[] {
  return SAMPLE_MEMORIES;
}

export function getMemoryById(id: string): MemoryItem | undefined {
  return SAMPLE_MEMORIES.find(m => m.id === id);
}

export function getMemoryOfTheDay(): MemoryItem {
  const featured = SAMPLE_MEMORIES.find(m => m.isMemoryOfTheDay);
  return featured || SAMPLE_MEMORIES[0];
}

export function getMemoriesByCategory(categoryKey: string): MemoryItem[] {
  if (!categoryKey || categoryKey === 'all') {
    return SAMPLE_MEMORIES;
  }
  return SAMPLE_MEMORIES.filter(m => m.category === categoryKey);
}
